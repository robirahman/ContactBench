"""Append-only run storage: JSONL decision/event logs plus a SQLite index.

The JSONL logs are the immutable source of truth.  The SQLite index and the
per-game JSON records are derived and can be regenerated by replay.
"""

from __future__ import annotations

import json
import os
import sqlite3
import tempfile
import threading
import time
from pathlib import Path
from typing import Any, Iterator


def atomic_write_json(path: Path, obj: Any) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    fd, tmp = tempfile.mkstemp(dir=path.parent, suffix=".tmp")
    with os.fdopen(fd, "w") as f:
        json.dump(obj, f, indent=2, sort_keys=True, default=str)
        f.write("\n")
        f.flush()
        os.fsync(f.fileno())
    os.replace(tmp, path)


def read_jsonl(path: Path) -> Iterator[dict]:
    if not path.exists():
        return
    with path.open() as f:
        for line in f:
            line = line.strip()
            if not line:
                continue
            try:
                yield json.loads(line)
            except json.JSONDecodeError:
                # A torn final line from a crash is ignored (never applied).
                continue


class RunStore:
    DECISIONS = "decisions.jsonl"
    REQUESTS = "requests.jsonl"
    EVENTS = "events.jsonl"

    def __init__(self, run_dir: str | Path):
        self.dir = Path(run_dir)
        self.dir.mkdir(parents=True, exist_ok=True)
        (self.dir / "games").mkdir(exist_ok=True)
        self._lock = threading.Lock()
        self._decisions: dict[str, dict] | None = None
        self._repaired: set[str] = set()
        self.duplicate_decisions: list[str] = []
        self.db = sqlite3.connect(self.dir / "index.sqlite", check_same_thread=False)
        self.db.executescript(
            """
            CREATE TABLE IF NOT EXISTS games (
                game_id TEXT PRIMARY KEY, fixture_id TEXT, task_id TEXT, attacker TEXT,
                defender TEXT, status TEXT, outcome_status TEXT, collection_status TEXT,
                cost_num INTEGER, cost_den INTEGER, updated_at REAL);
            CREATE TABLE IF NOT EXISTS decisions (
                decision_id TEXT PRIMARY KEY, game_id TEXT, seat TEXT, phase TEXT,
                status TEXT, recorded_at REAL);
            """
        )
        self.db.commit()

    # ----------------------------------------------------------------- append
    def _repair_tail(self, name: str) -> None:
        """Restore a record boundary after a crash left a partial final line.

        The torn bytes (never a complete, applied record) are moved to
        ``<name>.torn`` for audit and truncated from the log, so the next
        append starts on its own line instead of being fused to garbage.
        """
        path = self.dir / name
        if name in self._repaired or not path.exists():
            self._repaired.add(name)
            return
        with path.open("rb+") as f:
            f.seek(0, os.SEEK_END)
            size = f.tell()
            if size:
                f.seek(size - 1)
                if f.read(1) != b"\n":
                    f.seek(0)
                    data = f.read()
                    cut = data.rfind(b"\n") + 1
                    with (self.dir / f"{name}.torn").open("ab") as t:
                        t.write(data[cut:] + b"\n")
                    f.truncate(cut)
                    f.flush()
                    os.fsync(f.fileno())
        self._repaired.add(name)

    def _append(self, name: str, record: dict) -> None:
        line = json.dumps(record, sort_keys=True, default=str) + "\n"
        with self._lock:
            self._repair_tail(name)
            with (self.dir / name).open("a") as f:
                f.write(line)
                f.flush()
                os.fsync(f.fileno())

    def append_event(self, record: dict) -> None:
        record = {"ts": time.time(), **record}
        self._append(self.EVENTS, record)

    def append_request(self, record: dict) -> None:
        self._append(self.REQUESTS, {"ts": time.time(), **record})

    def record_decision(self, record: dict) -> bool:
        """Persist a received decision before it is applied.  Idempotent."""
        decisions = self.decisions()
        did = record["decision_id"]
        if did in decisions:
            self.duplicate_decisions.append(did)
            return False
        record = {"recorded_at": time.time(), **record}
        self._append(self.DECISIONS, record)
        decisions[did] = record
        with self._lock:
            self.db.execute(
                "INSERT OR IGNORE INTO decisions VALUES (?,?,?,?,?,?)",
                (did, record.get("game_id"), record.get("seat"), record.get("phase"), "received", record["recorded_at"]),
            )
            self.db.commit()
        return True

    def decisions(self) -> dict[str, dict]:
        if self._decisions is None:
            self._decisions = {}
            for rec in read_jsonl(self.dir / self.DECISIONS):
                did = rec["decision_id"]
                if did in self._decisions:
                    self.duplicate_decisions.append(did)
                    continue  # first received response wins
                self._decisions[did] = rec
        return self._decisions

    def events(self) -> list[dict]:
        return list(read_jsonl(self.dir / self.EVENTS))

    def requests(self) -> list[dict]:
        return list(read_jsonl(self.dir / self.REQUESTS))

    # ------------------------------------------------------------- game index
    def update_game(self, row: dict) -> None:
        with self._lock:
            self.db.execute(
                "INSERT OR REPLACE INTO games VALUES (?,?,?,?,?,?,?,?,?,?,?)",
                (
                    row["game_id"],
                    row.get("fixture_id"),
                    row.get("task_id"),
                    row.get("attacker"),
                    row.get("defender"),
                    row.get("status"),
                    row.get("outcome_status"),
                    row.get("collection_status"),
                    row.get("cost_num"),
                    row.get("cost_den"),
                    time.time(),
                ),
            )
            self.db.commit()

    def game_rows(self) -> list[dict]:
        cur = self.db.execute("SELECT * FROM games")
        cols = [c[0] for c in cur.description]
        return [dict(zip(cols, r)) for r in cur.fetchall()]

    def write_game(self, game_id: str, record: dict) -> None:
        atomic_write_json(self.dir / "games" / f"{game_id}.json", record)

    def read_game(self, game_id: str) -> dict | None:
        p = self.dir / "games" / f"{game_id}.json"
        return json.loads(p.read_text()) if p.exists() else None

    def write_json(self, name: str, obj: Any) -> None:
        atomic_write_json(self.dir / name, obj)

    def read_json(self, name: str) -> Any:
        return json.loads((self.dir / name).read_text())

    def close(self) -> None:
        self.db.close()
