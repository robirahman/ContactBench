"""Frozen clue bank and shadow forecast audit (spec Sections 8.4 and 8.6).

The item bank is built from saved pre-resolution observations regenerated by
replaying recorded decisions.  Items include blocked, canceled and opened
commitments under a predeclared deterministic sampling rule; selection never
depends on outcomes.  Answer keys stay in the referee-only bank file.
"""

